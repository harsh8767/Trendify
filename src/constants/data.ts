// Builds a sample product. Photo, colour and size fall back to simple defaults for the category,
// and any of them can be set on a single product to override the default.
function Product(details: SampleProductDetails): Product {
  const defaultPhotos: Record<string, string> = {
    Shoe: 'https://images.unsplash.com/photo-1542291026-7eec264c27ff?auto=format&fit=crop&w=600&q=80',
    Bag: 'https://images.unsplash.com/photo-1548036328-c9fa89d12891?auto=format&fit=crop&w=600&q=80',
    Luxury: 'https://images.unsplash.com/photo-1515562141207-7a88fb7ce338?auto=format&fit=crop&w=600&q=80',
    Kids: 'https://images.unsplash.com/photo-1760287363879-6012adab292c?auto=format&fit=crop&w=600&q=80',
    Sports: 'https://images.unsplash.com/photo-1542291026-7eec264c27ff?auto=format&fit=crop&w=600&q=80',
    Beauty: 'https://images.unsplash.com/photo-1596462502278-27bfdc403348?auto=format&fit=crop&w=600&q=80',
    Lifestyle: 'https://images.unsplash.com/photo-1521572163474-6864f9cf17ab?auto=format&fit=crop&w=600&q=80',
    Other: 'https://images.unsplash.com/photo-1484704849700-f032a568e944?auto=format&fit=crop&w=600&q=80',
  };
  const defaultSizes: Record<string, string> = { Shoe: '42', Kids: 'M', Sports: 'M' };

  return {
    ...details,
    color: details.color ?? 'Black',
    size: details.size ?? defaultSizes[details.category] ?? 'One Size',
    image: details.image ?? defaultPhotos[details.category],
    sold: details.reviews,
  };
}

